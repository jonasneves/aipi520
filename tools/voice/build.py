"""Rebuild docs/teach/voice.js (the VOICE timing object) from script.json + align/*.align.json + the mp3s.

script.json holds each clip's spoken text with markers:
  {hl:ref}...{/hl}  highlight the page elements whose data-ref names `ref` while these words play
  {d:id}            draw the stage item `id` on this word
  {dock:id}         fly the stage term `id` to its panel on this word
  |                 the step's state cue (the model moves) on this word
  [calm] etc.       ElevenLabs v4 delivery tags; spoken as delivery, never as words
align/<id>.align.json is the ElevenLabs /with-timestamps response for the generated text (or a cut of one).

Every time is clamped to the clip's duration, so no cue waits on the end-of-clip flush.
Run: python3 tools/voice/build.py   (needs ffprobe)
"""
import json, re, html, subprocess, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
AUDIO = os.path.join(ROOT, 'docs/teach/audio')
OUT = os.path.join(ROOT, 'docs/teach/voice.js')
srcs = json.load(open(os.path.join(HERE, 'script.json')))


def duration(cid):
    r = subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0',
                        os.path.join(AUDIO, cid + '.mp3')], capture_output=True, text=True)
    return float(r.stdout)


def build(cid, src):
    al = json.load(open(os.path.join(HERE, 'align', cid + '.align.json')))
    text = al['text']
    st = al['alignment']['character_start_times_seconds']
    en = al['alignment']['character_end_times_seconds']
    out, phr, draws, docks, cue, i, op = [], [], [], [], None, 0, None
    while i < len(src):
        m = re.match(r'\{(hl|d|dock):(\w+)\}', src[i:])
        if m:
            if m.group(1) == 'hl': op = (m.group(2), len(out))
            elif m.group(1) == 'd': draws.append([len(out), m.group(2)])
            else: docks.append([len(out), m.group(2)])
            i += m.end(); continue
        if src.startswith('{/hl}', i): phr.append([op[1], len(out), op[0]]); i += 5; continue
        if src[i] == '|': cue = len(out); i += 1; continue
        out.append(src[i]); i += 1
    gen = ''.join(out)
    if gen != text:
        assert gen.strip() == text, (cid, gen, text)
        lead = len(gen) - len(gen.lstrip())
        shift = lambda x: max(0, min(len(text) - 1, x - lead))
    else:
        shift = lambda x: min(len(text) - 1, x)
    d = round(duration(cid), 2)
    clamp = lambda t: min(round(t, 2), d)

    def tat(x):
        x = shift(x)
        while x < len(text) - 1 and text[x] == ' ': x += 1
        return clamp(st[x])
    at_end = lambda x: shift(x) >= len(text) - 1
    E = {'d': d,
         'h': [[tat(a), clamp(en[shift(b) - 1] + 0.35) if b > 0 else 0.4, ref] for a, b, ref in phr],
         'D': [[min(clamp(en[-1]) if at_end(a) else tat(a), round(d - 0.1, 2)), n] for a, n in draws],
         'K': [[min(clamp(en[-1] + 0.1) if at_end(a) else tat(a), round(d - 0.1, 2)), n] for a, n in docks]}
    if cue is not None: E['c'] = tat(cue)
    sents = []
    ph = [[shift(pa), shift(pb - 1) + 1, r] for pa, pb, r in phr]
    for m in re.finditer(r'[^.!?]+[.!?]+', text):
        a, b = m.start(), m.end()
        while True:
            t = re.match(r'\s*\[[a-z]+\]\s*|\s+', text[a:b])
            if t and t.end() > 0: a += t.end()
            else: break
        if a >= b: continue
        h, j = '', a
        while j < b:
            t = re.match(r'\[[a-z]+\]\s*', text[j:b])
            if t: j += t.end(); continue
            for k, (pa, pb, _) in enumerate(ph):
                if pa == j or (pa < a and j == a and pb > a): h += f'<span class="ph" data-h="{k}">'
            h += html.escape(text[j])
            for k, (pa, pb, _) in enumerate(ph):
                if pb == j + 1 or (pb > b and j == b - 1 and pa < b): h += '</span>'
            j += 1
        sents.append([clamp(st[a]), re.sub(r'\s+', ' ', h).strip()])
    E['s'] = sents
    return E


meta = {cid: build(cid, src) for cid, src in srcs.items()}
with open(OUT, 'w') as f:
    f.write('// Generated by tools/voice/build.py from tools/voice/script.json; do not edit by hand.\n')
    f.write('// Per clip: duration d, caption sentences s, highlights h [start, end, ref], stage draws D, docks K, state cue c.\n')
    f.write('const VOICE = ' + json.dumps(meta, separators=(',', ':'), ensure_ascii=False) + ';\n')
print('wrote', OUT, len(meta), 'clips')
